#!/usr/bin/env python3
"""Build tiny rare-character webfonts. Requires fonttools[woff] and brotli.

Download HanaMinA.otf and HanaMinB.otf from the release below into
.cache/modern-shijing first. This is a manual asset step, not a build dependency.
The fonts provide legible Unicode glyphs, not facsimiles of the source scans.
"""
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
RELEASE = "https://github.com/cjkvi/HanaMinAFDKO/releases/download/8.030/"
ASSETS = ROOT / "src/assets/fonts"
ASSETS.mkdir(parents=True, exist_ok=True)
data = ''.join((ROOT / path).read_text() for path in (
    'src/data/shijing-zhou-nan-pilot.json', 'src/data/shijing-modern.json',
    'public/collations/shijing-modern-index.json'))
needed = {ord(c) for c in data if 0x3400 <= ord(c) <= 0x4DBF or ord(c) >= 0x20000}
remaining = set(needed)
manifest = []
css = ["/* Generated by scripts/build-shijing-pilot-font.py; see fonts/NOTICE.txt. */"]

for part in ("A", "B"):
    source = ROOT / f".cache/modern-shijing/HanaMin{part}.otf"
    font = TTFont(source, recalcTimestamp=False)
    codes = sorted(remaining & font.getBestCmap().keys())
    if not codes:
        continue
    remaining.difference_update(codes)
    options = subset.Options()
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_languages = [0x409]
    options.layout_features = []
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=codes)
    sub.subset(font)
    family = f"Shijing Pilot Rare {part}"
    names = {1: family, 2: "Regular", 3: f"ShijingPilotRare{part}-1.0",
             4: family, 6: f"ShijingPilotRare{part}", 16: family, 17: "Regular"}
    for name in font["name"].names:
        if name.nameID in names:
            font["name"].setName(names[name.nameID], name.nameID, name.platformID,
                                 name.platEncID, name.langID)
    if "CFF " in font:
        cff = font["CFF "].cff
        cff.fontNames = [names[6]]
        cff.topDictIndex[0].FamilyName = family
        cff.topDictIndex[0].FullName = family
    font.flavor = "woff2"
    output = ASSETS / f"shijing-pilot-rare-{part.lower()}.woff2"
    font.save(output)
    check = TTFont(output)
    assert set(check.getBestCmap()) == set(codes), "Subset changed Unicode coverage"
    assert all(check.getBestCmap()[c] != ".notdef" for c in codes)
    ranges = ", ".join(f"U+{code:X}" for code in codes)
    css.append(f'''@font-face {{
  font-family: "Shijing Pilot Rare";
  src: url("./fonts/{output.name}") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  unicode-range: {ranges};
}}''')
    manifest.append({
        "file": output.name, "source": RELEASE + source.name,
        "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "bytes": output.stat().st_size, "codepoints": [f"U+{c:X}" for c in codes],
        "copyright": "2007-2018 GlyphWiki. All Rights Reserved.",
        "license": "GlyphWiki data and article usage licence; see NOTICE.txt",
    })

assert not remaining, f"Missing glyphs: {sorted(remaining)}"
(ASSETS.parent / "shijing-pilot-fonts.css").write_text("\n\n".join(css) + "\n")
(ASSETS / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
notices = ROOT / 'public/fonts'
notices.mkdir(exist_ok=True)
(notices / 'shijing-rare-NOTICE.txt').write_text(
    (ASSETS / 'NOTICE.txt').read_text() + '\n\n' + (ASSETS / 'glyphwiki-license.txt').read_text())
print(f"Verified {len(needed)} rare characters; {sum(x['bytes'] for x in manifest)} bytes")
